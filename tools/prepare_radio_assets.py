"""Convert the generated 4x2 sprite atlas to compact LVGL 8 indexed assets.

Pillow is needed only when regenerating; the C arrays are checked in.
Palette entries use LVGL's BGRA byte order, independent of RGB565 swap.
"""
import argparse
import hashlib
import json
import re
from pathlib import Path
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
LAYOUT = (ROOT / "main/apps/ui_radio_skin.h").read_text(encoding="utf-8")


def layout_dimension(name):
    match = re.search(r"^#define\s+" + name + r"\s+(\d+)\s*$", LAYOUT, re.M)
    if not match:
        raise ValueError(f"缺少画布尺寸定义：{name}")
    return int(match.group(1))


WIDTH = layout_dimension("RADIO_SKIN_ART_W")
HEIGHT = layout_dimension("RADIO_SKIN_ART_H")
CONTENT_PADDING = 6
assert WIDTH % 2 == 0 and min(WIDTH, HEIGHT) > 2 * CONTENT_PADDING
NAMES = ["host", "cat", "space", "sea", "rain", "robot", "garden", "host_paused"]
BACKGROUNDS = ["A98AFF", "FFE8B8", "071C44", "006675", "242448", "D7F0A0", "FFF29B", "A98AFF"]
NOTICE = "/* SPDX-License-Identifier: Apache-2.0\n * Copyright (c) 2026 深圳希德创新网络有限公司 (SDGOODS)\n * Generated by tools/prepare_radio_assets.py. Do not edit pixel data.\n */\n"


def preserved_notice(path):
    if not path.exists():
        return NOTICE
    source=path.read_text(encoding="utf-8")
    end=0
    while True:
        start=end
        while start<len(source) and source[start].isspace():start+=1
        if not source.startswith("/*",start):break
        stop=source.find("*/",start+2)
        if stop<0:break
        end=stop+2
    return source[:end]+"\n" if end else NOTICE


def convert(atlas, output):
    output.mkdir(parents=True, exist_ok=True)
    image = Image.open(atlas).convert("RGB")
    code = [preserved_notice(ROOT/"main/apps/ui_radio_assets.c"), '#include "ui_radio_assets.h"\n']
    header = [preserved_notice(ROOT/"main/apps/ui_radio_assets.h"), '#pragma once\n#include "lvgl.h"\n']
    manifest = {"source_sha256": hashlib.sha256(Path(atlas).read_bytes()).hexdigest(), "size": [WIDTH, HEIGHT], "format": "LV_IMG_CF_INDEXED_4BIT", "assets": []}
    for i, name in enumerate(NAMES):
        col, row = i % 4, i // 4
        bounds = tuple(round(v) for v in (col * image.width / 4, row * image.height / 2, (col + 1) * image.width / 4, (row + 1) * image.height / 2))
        # Keep the entire scene. Only discard the two-pixel atlas separators.
        cell = image.crop((bounds[0]+2,bounds[1]+2,bounds[2]-2,bounds[3]-2))
        # Color-key the generated matte for clean blending into each skin.
        border = [cell.getpixel((x, 2)) for x in range(2, cell.width - 2)]
        bg = tuple(sorted(p[c] for p in border)[len(border) // 2] for c in range(3))
        rgba = cell.convert("RGBA")
        pixels=cell.get_flattened_data() if hasattr(cell,"get_flattened_data") else cell.getdata()
        rgba.putdata([(*p, 0 if sum((p[c] - bg[c]) ** 2 for c in range(3)) < 42 ** 2 else 255) for p in pixels])
        box = rgba.getbbox()
        if not box:
            raise ValueError(f"empty generated sprite: {name}")
        sprite = ImageOps.contain(rgba.crop(box), (WIDTH-2*CONTENT_PADDING, HEIGHT-2*CONTENT_PADDING), Image.Resampling.NEAREST)
        canvas = Image.new("RGBA", (WIDTH, HEIGHT))
        canvas.paste(sprite, ((WIDTH - sprite.width) // 2, (HEIGHT - sprite.height) // 2))
        indexed = canvas.quantize(colors=16, method=Image.Quantize.FASTOCTREE, dither=Image.Dither.NONE)
        palette = indexed.getpalette("RGBA")
        data = bytearray()
        for j in range(16):
            r, g, b, a = palette[j * 4:j * 4 + 4]
            data.extend((b, g, r, a))
        indices = list(indexed.get_flattened_data() if hasattr(indexed,"get_flattened_data") else indexed.getdata())
        for j in range(0, len(indices), 2):
            data.append((indices[j] << 4) | indices[j + 1])
        assert len(data) == 64 + WIDTH * HEIGHT // 2
        # Byte-exact round-trip of palette and index packing.
        unpacked = [n for byte in data[64:] for n in (byte >> 4, byte & 15)]
        assert unpacked == indices
        visible=indexed.convert("RGBA").getbbox()
        assert visible and visible[0]>=CONTENT_PADDING and visible[1]>=CONTENT_PADDING
        assert visible[2]<=WIDTH-CONTENT_PADDING and visible[3]<=HEIGHT-CONTENT_PADDING
        indexed.save(output / f"{name}.png")
        preview = Image.new("RGBA", (WIDTH, HEIGHT), "#" + BACKGROUNDS[i])
        preview.alpha_composite(indexed.convert("RGBA"))
        preview.convert("RGB").save(output / f"{name}-matte.png")
        symbol = "radio_art_" + name
        header.append(f"LV_IMG_DECLARE({symbol});\n")
        code.append(f"static const uint8_t {symbol}_data[] = {{\n")
        code.extend("    " + ",".join(f"0x{b:02x}" for b in data[j:j + 24]) + ",\n" for j in range(0, len(data), 24))
        code.append("};\n")
        code.append(f"const lv_img_dsc_t {symbol} = {{.header = {{.cf = LV_IMG_CF_INDEXED_4BIT, .w = {WIDTH}, .h = {HEIGHT}}}, .data_size = sizeof({symbol}_data), .data = {symbol}_data}};\n\n")
        manifest["assets"].append({"name": name, "bytes": len(data), "sha256": hashlib.sha256(data).hexdigest(), "cell": i + 1,
                                   "source_content_bounds": list(box), "visible_bounds": list(visible), "padding": CONTENT_PADDING})
    (ROOT / "main/apps/ui_radio_assets.c").write_text("".join(code), encoding="utf-8")
    (ROOT / "main/apps/ui_radio_assets.h").write_text("".join(header), encoding="utf-8")
    (output / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(f"Converted {len(NAMES)} sprites; total image bytes {sum(a['bytes'] for a in manifest['assets'])}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--atlas", type=Path, required=True)
    args = parser.parse_args()
    convert(args.atlas, ROOT / "main/assets/radio")
