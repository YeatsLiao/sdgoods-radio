"""Generate a small high-resolution radio headline subset; uncommon names use the broad network font."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
ROOT=Path(__file__).resolve().parents[1]
CHARS="城市音乐台杭州交通经济广播华语之声网络中国中央人民北京上海广东深圳浙江江苏湖南湖北福建安徽山东四川重庆成都天津河北河南黑龙江吉林辽宁陕西山西云南贵州广西海南内蒙古新疆西藏宁夏青海甘肃香港澳门台湾温州宁波绍兴金嘉兴湖丽水衢舟扬南京苏锡常徐连镇泰盐淮宿合肥芜蚌埠马鞍宣阜阳六安滁池黄铜陵淮南北亳宿济青烟威潍临沂德聊滨枣庄菏日照东营太原大同运忻朔晋长治吕梁牡丹齐哈佳木斯绥化双鸭伊春鹤岗七河石家庄唐邯郸保定秦皇岛承廊衡沧张口郑洛开封焦作濮许昌漯驻店周平顶商丘鹤壁新乡武鄂荆襄宜咸感随恩施十堰黄冈石岳衡株潭郴永益娄邵常德怀张界长沙汕头尾惠潮湛茂肇庆佛珠韶梅江源揭清远汕阳云浮泉漳莆三明龙岩南平赣九景萍鹰吉抚饶宜福兰银呼和浩特包赤乌通辽鄂尔多斯巴彦淖兴盟锡林郭勒阿拉善昆曲玉昭普洱保山楚雄红河文山西双版纳大理德宏怒迪庆雅攀枝花乐眉遂绵泸宜自贡达巴广元资内凉甘阿坝贵遵毕安顺六盘黔东南西南铜仁贵阳兰银银川拉萨乌鲁木齐乌昌克玛依吐鲁番喀什伊犁和田库尔勒阿克苏国际生活新闻资讯故事戏曲经典流行怀旧都市轻调频汽车时尚少儿读书健康校园教育文艺旅游运动体育快乐纯爱听合"
def main():
    chars=sorted(set(CHARS),key=ord)
    font=ImageFont.truetype(str(ROOT/"tools/fonts/NotoSansSC-Regular.ttf"),32)
    data=bytearray(); desc=[(0,0,0,0,0,0)]
    for ch in chars:
        l,t,r,b=font.getbbox(ch,anchor="ls",stroke_width=1)
        image=Image.new("L",(r-l,b-t))
        ImageDraw.Draw(image).text((-l,-t),ch,font=font,anchor="ls",fill=255,stroke_width=1,stroke_fill=255)
        pixels=list(image.get_flattened_data())
        offset=len(data)
        for i in range(0,len(pixels),4):
            packed=0
            for j in range(4):
                alpha=(pixels[i+j]*3+127)//255 if i+j<len(pixels) else 0
                packed|=alpha<<(6-j*2)
            data.append(packed)
        desc.append((offset,round(font.getlength(ch)*16),r-l,b-t,l,-b))
    out=["/* Generated by tools/prepare_radio_title_font.py.",
         " * Glyphs derived from Noto Sans SC, Copyright (c) 2014-2021 Adobe.",
         " * Reserved Font Name: Source. Bitmap font licensed under SIL OFL 1.1.",
         " * SPDX-License-Identifier: OFL-1.1",
         " * See components/sdgoods_board/fonts/OFL.txt; preserve this notice when redistributing.", " */",
         '#include "lvgl.h"', "static const uint8_t bitmap[]={"]
    for i in range(0,len(data),24):out.append(",".join(f"0x{x:02x}" for x in data[i:i+24])+",")
    out+=["};","static const lv_font_fmt_txt_glyph_dsc_t glyphs[]={"]
    for offset,adv,w,h,x,y in desc:
        out.append(f"{{.bitmap_index={offset},.adv_w={adv},.box_w={w},.box_h={h},.ofs_x={x},.ofs_y={y}}},")
    out+=["};","static const uint16_t unicode_list[]={",",".join(str(ord(ch)-ord(chars[0])) for ch in chars),"};",
          "static const lv_font_fmt_txt_cmap_t cmaps[]={",
          f"{{.range_start={ord(chars[0])},.range_length={ord(chars[-1])-ord(chars[0])+1},.glyph_id_start=1,.unicode_list=unicode_list,.glyph_id_ofs_list=NULL,.list_length={len(chars)},.type=LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}}",
          "};","static lv_font_fmt_txt_glyph_cache_t cache;",
          "static lv_font_fmt_txt_dsc_t dsc={.glyph_bitmap=bitmap,.glyph_dsc=glyphs,.cmaps=cmaps,.cmap_num=1,.bpp=2,.bitmap_format=0,.cache=&cache};",
          "const lv_font_t radio_title_32={.get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,.get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,.line_height=40,.base_line=10,.dsc=&dsc};"]
    dest=ROOT/"main/apps/ui_radio_title_font.c"
    dest.write_text("\n".join(out)+"\n",encoding="utf-8")
    print(f"Headline subset: {len(chars)} glyphs, {len(data):,} bitmap bytes -> {dest}")
if __name__=="__main__":main()

