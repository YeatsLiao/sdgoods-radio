"""Extract illustration-only crops from approved concepts into LVGL source arrays.

Never include the mockup's station name, frequency, clock or playback controls.
This is source asset preparation; it does not build firmware.
"""
import hashlib
import json
import re
from pathlib import Path
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'docs/design/radio-v3/proposals/vinyl-redraw-20261030'
OUT = ROOT / 'main/assets/radio/redraw'
LAYOUT=(ROOT/'main/apps/ui_radio_skin.h').read_text(encoding='utf-8')


def dimension(name):
    return int(re.search(r'^#define\s+'+name+r'\s+(\d+)\s*$',LAYOUT,re.M)[1])


SPECS = [
    ('vinyl_pop', 'A-pop-vinyl.png', (232, 194, 1030, 742), (240, 140), (249, 245, 237)),
    ('vinyl_pixel', 'B-pixel-deck.png', (244, 224, 1030, 748), (240, 140), (216, 248, 227)),
    ('vinyl_night', 'C-night-vinyl.png', (224, 207, 1090, 715), (240, 140), (26, 25, 63)),
    # Landscape only. The original pointer and numeric scale are excluded.
    ('paper_scene', 'paper-approved-reference.png', (979, 416, 1660, 478),
     (dimension('RADIO_PAPER_SCENE_W'),dimension('RADIO_PAPER_SCENE_H')), None),
]
NOTICE = '/* SPDX-License-Identifier: Apache-2.0\n * Copyright (c) 2026 深圳希德创新网络有限公司 (SDGOODS)\n * Generated by tools/prepare_radio_redraw.py; retain NOTICE.\n */\n'


def notice(filename):
    path=ROOT/'main/apps'/filename
    if not path.exists():return NOTICE
    source=path.read_text(encoding='utf-8');end=0
    while True:
        start=end
        while start<len(source) and source[start].isspace():start+=1
        if not source.startswith('/*',start):break
        stop=source.find('*/',start+2)
        if stop<0:break
        end=stop+2
    return source[:end]+'\n' if end else NOTICE


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    code = [notice('ui_radio_redraw_assets.c'), '#include "ui_radio_redraw_assets.h"\n']
    header = [notice('ui_radio_redraw_assets.h'), '#pragma once\n#include "lvgl.h"\n']
    manifest = []
    for name, filename, box, size, bg in SPECS:
        source = SOURCE / filename
        image = Image.open(source).convert('RGB').crop(box).convert('RGBA')
        if name=='vinyl_night':
            pixels=list(image.get_flattened_data())
            image.putdata([(*p[:3],0 if (box[0]+i%image.width-627)**2+(box[1]+i//image.width-618)**2>585**2 else p[3]) for i,p in enumerate(pixels)])
        if bg:
            pixels = image.get_flattened_data()
            image.putdata([(*p[:3], 0 if sum((p[i]-bg[i])**2 for i in range(3)) < 38**2 else p[3]) for p in pixels])
        resized = ImageOps.contain(image, (size[0]-12, size[1]-12) if bg else size,
                                   Image.Resampling.NEAREST if name=='vinyl_pixel' else Image.Resampling.LANCZOS)
        canvas = Image.new('RGBA', size)
        canvas.alpha_composite(resized, ((size[0]-resized.width)//2, (size[1]-resized.height)//2))
        # Binary alpha reserves the available palette entries for illustration colors.
        alpha=canvas.getchannel('A').point(lambda a:255 if a>=128 else 0)
        canvas.putalpha(alpha)
        indexed=canvas.quantize(colors=64 if bg else 16,method=Image.Quantize.FASTOCTREE,dither=Image.Dither.NONE)
        palette=indexed.getpalette('RGBA')
        palette+= [0]*(1024-len(palette))
        data=bytearray()
        entries=256 if bg else 16
        for j in range(entries):
            r,g,b,a=palette[j*4:j*4+4]
            data.extend((b,g,r,a))
        indices=list(indexed.get_flattened_data())
        if bg:data.extend(indices)
        else:
            for j in range(0,len(indices),2):data.append((indices[j]<<4)|indices[j+1])
        assert len(data)==entries*4+size[0]*size[1]//(1 if bg else 2)
        assert (list(data[1024:]) if bg else [n for b in data[64:] for n in (b>>4,b&15)])==indices
        indexed.save(OUT/f'{name}.png')
        symbol='radio_art_'+name
        header.append(f'LV_IMG_DECLARE({symbol});\n')
        code.append(f'static const uint8_t {symbol}_data[] = {{\n')
        code.extend('    '+','.join(f'0x{b:02x}' for b in data[j:j+24])+',\n' for j in range(0,len(data),24))
        code.append('};\n')
        fmt='LV_IMG_CF_INDEXED_8BIT' if bg else 'LV_IMG_CF_INDEXED_4BIT'
        code.append(f'const lv_img_dsc_t {symbol} = {{.header={{.cf={fmt},.w={size[0]},.h={size[1]}}},.data_size=sizeof({symbol}_data),.data={symbol}_data}};\n')
        manifest.append(dict(name=name,source=filename,source_sha256=hashlib.sha256(source.read_bytes()).hexdigest(),crop=box,
                             size=size,bytes=len(data),sha256=hashlib.sha256(data).hexdigest(),visible_bounds=indexed.convert('RGBA').getbbox()))
    (ROOT/'main/apps/ui_radio_redraw_assets.c').write_text(''.join(code),encoding='utf-8')
    (ROOT/'main/apps/ui_radio_redraw_assets.h').write_text(''.join(header),encoding='utf-8')
    (OUT/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n',encoding='utf-8')
    print('Illustration sources:',len(manifest),'bytes:',sum(x['bytes'] for x in manifest))


if __name__=='__main__':main()
